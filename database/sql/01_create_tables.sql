-- ====================================================================
-- AI HEALTH CLINIC - ORACLE DATABASE SCHEMA
-- Script 01: Table Creation
-- Compatible with Oracle Database 19c, 21c, 23c, and Oracle Live SQL
-- ====================================================================

-- 1. USERS: Core authentication and identity table
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(255) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'patient' NOT NULL CHECK (ROLE IN ('patient', 'doctor', 'admin')),
    FULL_NAME VARCHAR2(150) NOT NULL,
    PHONE VARCHAR2(20),
    IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1)),
    IS_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL CHECK (IS_VERIFIED IN (0, 1)),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. PATIENT_PROFILES: Specific medical and personal details for patients
CREATE TABLE PATIENT_PROFILES (
    PATIENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR2(20) CHECK (GENDER IN ('Male', 'Female', 'Other', 'Prefer not to say')),
    BLOOD_GROUP VARCHAR2(10) CHECK (BLOOD_GROUP IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-')),
    EMERGENCY_CONTACT_NAME VARCHAR2(100),
    EMERGENCY_CONTACT_PHONE VARCHAR2(20),
    KNOWN_ALLERGIES CLOB,
    CHRONIC_CONDITIONS CLOB,
    CURRENT_MEDICATIONS CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. DOCTOR_PROFILES: Professional details and verification status
CREATE TABLE DOCTOR_PROFILES (
    DOCTOR_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL UNIQUE REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    SPECIALIZATION VARCHAR2(100) NOT NULL,
    QUALIFICATION_SUMMARY VARCHAR2(200) NOT NULL,
    EXPERIENCE_YEARS NUMBER DEFAULT 0 NOT NULL,
    MEDICAL_REG_NUMBER VARCHAR2(50) NOT NULL UNIQUE,
    REGISTRATION_COUNCIL VARCHAR2(150) NOT NULL,
    CONSULTATION_FEE NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    VERIFICATION_STATUS VARCHAR2(30) DEFAULT 'Pending' NOT NULL 
        CHECK (VERIFICATION_STATUS IN ('Submitted', 'Pending', 'Under review', 'Additional info required', 'Verified', 'Rejected', 'Suspended')),
    BIO CLOB,
    RATING NUMBER(3, 2) DEFAULT 5.00,
    TOTAL_REVIEWS NUMBER DEFAULT 0,
    AVATAR_URL VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 4. USER_CONSENTS: Legal, privacy, and data processing consents
CREATE TABLE USER_CONSENTS (
    CONSENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSENT_TYPE VARCHAR2(50) NOT NULL,
    IS_GRANTED NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_GRANTED IN (0, 1)),
    IP_ADDRESS VARCHAR2(45),
    GRANTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REVOKED_AT TIMESTAMP
);

-- 5. RECORD_SHARING_PERMISSIONS: Fine-grained patient-to-doctor sharing controls
CREATE TABLE RECORD_SHARING_PERMISSIONS (
    PERMISSION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    DOCTOR_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CAN_VIEW_REPORTS NUMBER(1) DEFAULT 1 NOT NULL CHECK (CAN_VIEW_REPORTS IN (0, 1)),
    CAN_VIEW_TIMELINE NUMBER(1) DEFAULT 1 NOT NULL CHECK (CAN_VIEW_TIMELINE IN (0, 1)),
    CAN_VIEW_MEDICINES NUMBER(1) DEFAULT 1 NOT NULL CHECK (CAN_VIEW_MEDICINES IN (0, 1)),
    EXPIRES_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 6. DOCTOR_APPLICATIONS: Onboarding and credential submission
CREATE TABLE DOCTOR_APPLICATIONS (
    APPLICATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DOCTOR_ID NUMBER NOT NULL REFERENCES DOCTOR_PROFILES(DOCTOR_ID) ON DELETE CASCADE,
    STATUS VARCHAR2(30) DEFAULT 'Pending' NOT NULL,
    SUBMITTED_ON TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    REVIEWED_BY_ADMIN_ID NUMBER REFERENCES USERS(USER_ID),
    REVIEW_NOTES CLOB,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 7. DOCTOR_QUALIFICATIONS: Degrees, diplomas, and institutions
CREATE TABLE DOCTOR_QUALIFICATIONS (
    QUALIFICATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    APPLICATION_ID NUMBER NOT NULL REFERENCES DOCTOR_APPLICATIONS(APPLICATION_ID) ON DELETE CASCADE,
    DEGREE_NAME VARCHAR2(100) NOT NULL,
    INSTITUTION_NAME VARCHAR2(200) NOT NULL,
    YEAR_OF_COMPLETION NUMBER(4) NOT NULL,
    NAD_RECORD_ID VARCHAR2(100),
    IS_DIGILOCKER_VERIFIED NUMBER(1) DEFAULT 0 CHECK (IS_DIGILOCKER_VERIFIED IN (0, 1))
);

-- 8. DOCTOR_REGISTRATIONS: State council or NMC registration checks
CREATE TABLE DOCTOR_REGISTRATIONS (
    REGISTRATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    APPLICATION_ID NUMBER NOT NULL REFERENCES DOCTOR_APPLICATIONS(APPLICATION_ID) ON DELETE CASCADE,
    REGISTRATION_NUMBER VARCHAR2(50) NOT NULL,
    COUNCIL_NAME VARCHAR2(150) NOT NULL,
    REGISTRATION_YEAR NUMBER(4) NOT NULL,
    NMC_REGISTER_STATUS VARCHAR2(50) DEFAULT 'Manual review required',
    CHECK_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. DOCTOR_VERIFICATION_EVIDENCE: Uploaded identity and degree certificates
CREATE TABLE DOCTOR_VERIFICATION_EVIDENCE (
    EVIDENCE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    APPLICATION_ID NUMBER NOT NULL REFERENCES DOCTOR_APPLICATIONS(APPLICATION_ID) ON DELETE CASCADE,
    DOCUMENT_TYPE VARCHAR2(50) NOT NULL, -- 'Degree Certificate', 'Registration Certificate', 'Govt ID'
    FILE_NAME VARCHAR2(255) NOT NULL,
    STORAGE_PATH VARCHAR2(500) NOT NULL,
    FILE_SIZE_BYTES NUMBER NOT NULL,
    UPLOADED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    OCR_EXTRACTED_TEXT CLOB,
    VERIFICATION_RESULT VARCHAR2(50) DEFAULT 'Pending'
);

-- 10. DOCTOR_VERIFICATION_REVIEWS: Audit trail of administrator review actions
CREATE TABLE DOCTOR_VERIFICATION_REVIEWS (
    REVIEW_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    APPLICATION_ID NUMBER NOT NULL REFERENCES DOCTOR_APPLICATIONS(APPLICATION_ID) ON DELETE CASCADE,
    ADMIN_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID),
    ACTION_TAKEN VARCHAR2(50) NOT NULL, -- 'Approved', 'Rejected', 'Requested Info'
    REASON_DESCRIPTION CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 11. MEDICAL_REPORTS: Patient uploaded medical reports & test documents
CREATE TABLE MEDICAL_REPORTS (
    REPORT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    REPORT_TITLE VARCHAR2(200) NOT NULL,
    REPORT_CATEGORY VARCHAR2(50) DEFAULT 'Other' NOT NULL, -- 'Blood Tests', 'Imaging', 'Prescriptions', 'Other'
    TEST_NAME VARCHAR2(200),
    TEST_DATE DATE,
    REPORT_ISSUE_DATE DATE,
    UPLOAD_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ISSUING_LAB_OR_HOSPITAL VARCHAR2(200),
    FILE_NAME VARCHAR2(255) NOT NULL,
    FILE_STORAGE_PATH VARCHAR2(500) NOT NULL,
    FILE_SIZE_BYTES NUMBER NOT NULL,
    FILE_MIME_TYPE VARCHAR2(100) NOT NULL,
    PROCESSING_STATUS VARCHAR2(30) DEFAULT 'Completed' NOT NULL,
    EXTRACTED_RAW_TEXT CLOB,
    DOCTOR_INTERPRETATION CLOB,
    DOCTOR_FOLLOW_UP_NOTES CLOB,
    VERSION_NUMBER NUMBER DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 12. REPORT_SUMMARIES: AI grounded explanations of lab reports
CREATE TABLE REPORT_SUMMARIES (
    SUMMARY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REPORT_ID NUMBER NOT NULL UNIQUE REFERENCES MEDICAL_REPORTS(REPORT_ID) ON DELETE CASCADE,
    AI_SUMMARY_TEXT CLOB NOT NULL,
    KEY_FINDINGS CLOB,
    NORMAL_METRICS CLOB,
    ABNORMAL_METRICS CLOB,
    QUESTIONS_FOR_DOCTOR CLOB,
    SOURCE_GROUNDING_DISCLAIMER VARCHAR2(500) DEFAULT 'AI-generated summary based strictly on document text. Not a clinical diagnosis.',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 13. REPORT_EXTRACTED_MEASUREMENTS: Structured lab test metrics with reference ranges
CREATE TABLE REPORT_EXTRACTED_MEASUREMENTS (
    MEASUREMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REPORT_ID NUMBER NOT NULL REFERENCES MEDICAL_REPORTS(REPORT_ID) ON DELETE CASCADE,
    TEST_METRIC_NAME VARCHAR2(100) NOT NULL,
    OBSERVED_VALUE NUMBER(10, 3) NOT NULL,
    UNIT VARCHAR2(30) NOT NULL,
    REFERENCE_RANGE_LOW NUMBER(10, 3),
    REFERENCE_RANGE_HIGH NUMBER(10, 3),
    STATUS_FLAG VARCHAR2(20) DEFAULT 'Normal' CHECK (STATUS_FLAG IN ('Low', 'Normal', 'High', 'Critical')),
    NOTES VARCHAR2(255)
);

-- 14. AI_CONSULTATIONS: Cautious symptom triage & guidance sessions
CREATE TABLE AI_CONSULTATIONS (
    CONSULTATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    SESSION_TITLE VARCHAR2(200) DEFAULT 'General Consultation' NOT NULL,
    CHIEF_COMPLAINT VARCHAR2(500),
    TRIAGE_LEVEL VARCHAR2(30) DEFAULT 'Routine' CHECK (TRIAGE_LEVEL IN ('Emergency', 'Urgent', 'Routine', 'Self-Care')),
    SUMMARY CLOB,
    RECOMMENDED_ACTION CLOB,
    MEDICAL_SOURCES_CITED CLOB,
    STARTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ENDED_AT TIMESTAMP
);

-- 15. AI_CONSULTATION_MESSAGES: Dialogue history between user and assistant
CREATE TABLE AI_CONSULTATION_MESSAGES (
    MESSAGE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CONSULTATION_ID NUMBER NOT NULL REFERENCES AI_CONSULTATIONS(CONSULTATION_ID) ON DELETE CASCADE,
    SENDER_ROLE VARCHAR2(20) NOT NULL CHECK (SENDER_ROLE IN ('user', 'assistant', 'system')),
    MESSAGE_CONTENT CLOB NOT NULL,
    IS_URGENT_WARNING NUMBER(1) DEFAULT 0 CHECK (IS_URGENT_WARNING IN (0, 1)),
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 16. APPOINTMENTS: Doctor bookings & consultation schedules
CREATE TABLE APPOINTMENTS (
    APPOINTMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    DOCTOR_ID NUMBER NOT NULL REFERENCES DOCTOR_PROFILES(DOCTOR_ID) ON DELETE CASCADE,
    APPOINTMENT_DATE DATE NOT NULL,
    APPOINTMENT_TIME VARCHAR2(20) NOT NULL,
    CONSULTATION_TYPE VARCHAR2(20) DEFAULT 'Online' CHECK (CONSULTATION_TYPE IN ('Online', 'In-Person')),
    STATUS VARCHAR2(20) DEFAULT 'Confirmed' CHECK (STATUS IN ('Requested', 'Confirmed', 'Completed', 'Cancelled', 'Rescheduled')),
    REASON_FOR_VISIT VARCHAR2(500),
    DOCTOR_NOTES CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 17. DOCTOR_AVAILABILITY: Configurable slots for verified clinicians
CREATE TABLE DOCTOR_AVAILABILITY (
    AVAILABILITY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DOCTOR_ID NUMBER NOT NULL REFERENCES DOCTOR_PROFILES(DOCTOR_ID) ON DELETE CASCADE,
    DAY_OF_WEEK VARCHAR2(20) NOT NULL,
    START_TIME VARCHAR2(10) NOT NULL,
    END_TIME VARCHAR2(10) NOT NULL,
    IS_ACTIVE NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1))
);

-- 18. PATIENT_HEALTH_OBSERVATIONS: Self-recorded vitals & logs
CREATE TABLE PATIENT_HEALTH_OBSERVATIONS (
    OBSERVATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    OBSERVATION_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
    OBSERVATION_TYPE VARCHAR2(50) NOT NULL, -- 'Blood Pressure', 'Blood Glucose', 'Weight', 'Temperature', 'Symptom'
    MEASURED_VALUE VARCHAR2(100) NOT NULL,
    UNIT VARCHAR2(30),
    NOTES VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 19. MEDICINES: Verified medicine catalog for reference & education
CREATE TABLE MEDICINES (
    MEDICINE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    GENERIC_NAME VARCHAR2(150) NOT NULL,
    BRAND_NAMES VARCHAR2(300),
    DRUG_CLASS VARCHAR2(100),
    COMMON_USES CLOB,
    DOSAGE_FORMS VARCHAR2(200),
    PRECAUTIONS CLOB,
    CONTRAINDICATIONS CLOB,
    POTENTIAL_SIDE_EFFECTS CLOB,
    INTERACTION_WARNINGS CLOB,
    IS_PRESCRIPTION_REQUIRED NUMBER(1) DEFAULT 0 CHECK (IS_PRESCRIPTION_REQUIRED IN (0, 1)),
    SOURCE_REFERENCE VARCHAR2(300)
);

-- 20. PRESCRIPTIONS: Authorized prescriptions created by verified clinicians
CREATE TABLE PRESCRIPTIONS (
    PRESCRIPTION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    DOCTOR_ID NUMBER NOT NULL REFERENCES DOCTOR_PROFILES(DOCTOR_ID) ON DELETE CASCADE,
    APPOINTMENT_ID NUMBER REFERENCES APPOINTMENTS(APPOINTMENT_ID),
    DIAGNOSIS VARCHAR2(300) NOT NULL,
    INSTRUCTIONS CLOB,
    DATE_ISSUED DATE DEFAULT CURRENT_DATE NOT NULL,
    VALID_UNTIL DATE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 21. PRESCRIPTION_ITEMS: Detailed medication items per prescription
CREATE TABLE PRESCRIPTION_ITEMS (
    ITEM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PRESCRIPTION_ID NUMBER NOT NULL REFERENCES PRESCRIPTIONS(PRESCRIPTION_ID) ON DELETE CASCADE,
    MEDICINE_NAME VARCHAR2(150) NOT NULL,
    DOSAGE VARCHAR2(100) NOT NULL,
    FREQUENCY VARCHAR2(100) NOT NULL,
    DURATION VARCHAR2(50) NOT NULL,
    SPECIAL_INSTRUCTIONS VARCHAR2(300)
);

-- 22. MEDICINE_REMINDERS: Patient adherence reminders
CREATE TABLE MEDICINE_REMINDERS (
    REMINDER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    MEDICINE_NAME VARCHAR2(150) NOT NULL,
    DOSAGE VARCHAR2(100) NOT NULL,
    REMINDER_TIME VARCHAR2(10) NOT NULL, -- HH:MM (24 hr)
    DAYS_OF_WEEK VARCHAR2(100) DEFAULT 'Daily',
    START_DATE DATE DEFAULT CURRENT_DATE NOT NULL,
    END_DATE DATE,
    IS_ACTIVE NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 23. PHARMACY_PROVIDERS: Supported official external pharmacy destinations
CREATE TABLE PHARMACY_PROVIDERS (
    PROVIDER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PROVIDER_NAME VARCHAR2(100) NOT NULL UNIQUE,
    BASE_URL VARCHAR2(300) NOT NULL,
    SEARCH_URL_TEMPLATE VARCHAR2(500),
    CATEGORY_TAG VARCHAR2(50) DEFAULT 'Pharmacy',
    IS_ACTIVE NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
    INTEGRATION_STATUS VARCHAR2(50) DEFAULT 'External Link Only',
    LOGO_URL VARCHAR2(300),
    DISCLAIMER_TEXT VARCHAR2(500)
);

-- 24. HEALTH_TIMELINE_EVENTS: Central unified health journey ledger
CREATE TABLE HEALTH_TIMELINE_EVENTS (
    EVENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PATIENT_USER_ID NUMBER NOT NULL REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    EVENT_TYPE VARCHAR2(50) NOT NULL, -- 'Report Upload', 'AI Consultation', 'Doctor Consultation', 'Prescription', 'Health Observation'
    EVENT_TITLE VARCHAR2(200) NOT NULL,
    EVENT_DATE DATE NOT NULL,
    EVENT_TIME VARCHAR2(20),
    SHORT_DESCRIPTION VARCHAR2(500),
    ORGANIZATION_OR_DOCTOR VARCHAR2(200),
    RECORD_REFERENCE_ID NUMBER,
    STATUS_BADGE VARCHAR2(50) DEFAULT 'Completed',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 25. AUDIT_LOGS: Security, privacy, and access audit records
CREATE TABLE AUDIT_LOGS (
    LOG_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER REFERENCES USERS(USER_ID) ON DELETE SET NULL,
    ACTION_PERFORMED VARCHAR2(100) NOT NULL,
    RESOURCE_ACCESSED VARCHAR2(200),
    IP_ADDRESS VARCHAR2(45),
    STATUS VARCHAR2(20) DEFAULT 'SUCCESS',
    DETAILS CLOB,
    TIMESTAMP TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
