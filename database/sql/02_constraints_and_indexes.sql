-- Performance Indexes for High-Frequency Patient Queries
CREATE INDEX IDX_USERS_EMAIL ON USERS(EMAIL);
CREATE INDEX IDX_USERS_ROLE ON USERS(ROLE);

CREATE INDEX IDX_PATIENT_USER ON PATIENT_PROFILES(USER_ID);
CREATE INDEX IDX_DOCTOR_USER ON DOCTOR_PROFILES(USER_ID);
CREATE INDEX IDX_DOCTOR_STATUS ON DOCTOR_PROFILES(VERIFICATION_STATUS);
CREATE INDEX IDX_DOCTOR_SPEC ON DOCTOR_PROFILES(SPECIALIZATION);

-- Reports Indexes
CREATE INDEX IDX_REPORTS_PATIENT ON MEDICAL_REPORTS(PATIENT_USER_ID);
CREATE INDEX IDX_REPORTS_TEST_DATE ON MEDICAL_REPORTS(TEST_DATE);
CREATE INDEX IDX_REPORTS_CATEGORY ON MEDICAL_REPORTS(REPORT_CATEGORY);
CREATE INDEX IDX_MEASURE_REPORT ON REPORT_EXTRACTED_MEASUREMENTS(REPORT_ID);

-- Consultations & Appointments Indexes
CREATE INDEX IDX_AI_CONSULT_PATIENT ON AI_CONSULTATIONS(PATIENT_USER_ID);
CREATE INDEX IDX_MESSAGES_CONSULT ON AI_CONSULTATION_MESSAGES(CONSULTATION_ID);
CREATE INDEX IDX_APPT_PATIENT ON APPOINTMENTS(PATIENT_USER_ID);
CREATE INDEX IDX_APPT_DOCTOR ON APPOINTMENTS(DOCTOR_ID);
CREATE INDEX IDX_APPT_DATE ON APPOINTMENTS(APPOINTMENT_DATE, APPOINTMENT_TIME);

-- Health Timeline Performance Indexes
CREATE INDEX IDX_TIMELINE_PATIENT_DATE ON HEALTH_TIMELINE_EVENTS(PATIENT_USER_ID, EVENT_DATE DESC);
CREATE INDEX IDX_TIMELINE_TYPE ON HEALTH_TIMELINE_EVENTS(EVENT_TYPE);

-- Audit & Security Indexes
CREATE INDEX IDX_AUDIT_USER_TIME ON AUDIT_LOGS(USER_ID, TIMESTAMP DESC);
CREATE INDEX IDX_SHARING_PATIENT ON RECORD_SHARING_PERMISSIONS(PATIENT_USER_ID);
CREATE INDEX IDX_SHARING_DOCTOR ON RECORD_SHARING_PERMISSIONS(DOCTOR_USER_ID);

-- Reminders & Prescriptions Indexes
CREATE INDEX IDX_REMINDERS_PATIENT ON MEDICINE_REMINDERS(PATIENT_USER_ID);
CREATE INDEX IDX_PRESCRIPTIONS_PATIENT ON PRESCRIPTIONS(PATIENT_USER_ID);
