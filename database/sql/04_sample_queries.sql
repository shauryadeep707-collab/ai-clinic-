-- 1. UNIFIED TIMELINE: Retrieve chronological medical history for Patient Rohan Sharma (User ID 1)
SELECT 
    EVENT_ID,
    EVENT_TYPE,
    EVENT_TITLE,
    TO_CHAR(EVENT_DATE, 'DD Mon YYYY') AS FORMATTED_DATE,
    EVENT_TIME,
    SHORT_DESCRIPTION,
    ORGANIZATION_OR_DOCTOR,
    STATUS_BADGE
FROM HEALTH_TIMELINE_EVENTS
WHERE PATIENT_USER_ID = 1
ORDER BY EVENT_DATE DESC, EVENT_ID DESC;

-- 2. LAB METRICS COMPARISON: Compare blood test values across historical reports
SELECT 
    r.REPORT_TITLE,
    TO_CHAR(r.TEST_DATE, 'YYYY-MM-DD') AS TEST_DATE,
    m.TEST_METRIC_NAME,
    m.OBSERVED_VALUE,
    m.UNIT,
    m.REFERENCE_RANGE_LOW || ' - ' || m.REFERENCE_RANGE_HIGH AS REFERENCE_RANGE,
    m.STATUS_FLAG
FROM MEDICAL_REPORTS r
JOIN REPORT_EXTRACTED_MEASUREMENTS m ON r.REPORT_ID = m.REPORT_ID
WHERE r.PATIENT_USER_ID = 1
ORDER BY m.TEST_METRIC_NAME, r.TEST_DATE DESC;

-- 3. DOCTOR VERIFICATION QUEUE: Administrator pending review dashboard
SELECT 
    a.APPLICATION_ID,
    u.FULL_NAME AS DOCTOR_NAME,
    d.SPECIALIZATION,
    d.QUALIFICATION_SUMMARY,
    d.MEDICAL_REG_NUMBER,
    d.REGISTRATION_COUNCIL,
    TO_CHAR(a.SUBMITTED_ON, 'DD Mon YYYY HH24:MI') AS SUBMISSION_TIME,
    a.STATUS
FROM DOCTOR_APPLICATIONS a
JOIN DOCTOR_PROFILES d ON a.DOCTOR_ID = d.DOCTOR_ID
JOIN USERS u ON d.USER_ID = u.USER_ID
WHERE a.STATUS = 'Pending'
ORDER BY a.SUBMITTED_ON ASC;

-- 4. TODAY'S APPOINTMENTS: Clinician daily view
SELECT 
    apt.APPOINTMENT_ID,
    u_pat.FULL_NAME AS PATIENT_NAME,
    apt.APPOINTMENT_TIME,
    apt.CONSULTATION_TYPE,
    apt.STATUS,
    apt.REASON_FOR_VISIT
FROM APPOINTMENTS apt
JOIN USERS u_pat ON apt.PATIENT_USER_ID = u_pat.USER_ID
WHERE apt.DOCTOR_ID = 1
  AND apt.APPOINTMENT_DATE = CURRENT_DATE
ORDER BY apt.APPOINTMENT_TIME ASC;

-- 5. PATIENT SECURITY & AUDIT TRAIL: Inspect all access to sensitive records
SELECT 
    l.TIMESTAMP,
    l.ACTION_PERFORMED,
    l.RESOURCE_ACCESSED,
    l.IP_ADDRESS,
    l.STATUS
FROM AUDIT_LOGS l
WHERE l.USER_ID = 1
ORDER BY l.TIMESTAMP DESC;
